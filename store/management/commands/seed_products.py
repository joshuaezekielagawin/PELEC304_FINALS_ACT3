class Command(BaseCommand):
    help = 'Seed shiked6 music store with 24 popular instruments and music sheets.'

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0
        for item in SEED_PRODUCTS:
            obj, created = Product.objects.update_or_create(
                name=item['name'],
                defaults=item,
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

        total = Product.objects.count()
        self.stdout.write(
            self.style.SUCCESS(
                f'Seed complete: {created_count} created, {updated_count} updated. Total products in DB: {total}'
            )
        )
